// Writes public/THIRD_PARTY_NOTICES.txt: the licence notice of every production dependency
// (package-lock.json, entries not marked dev), so the zips carry them. Run after changing
// dependencies:  npm run licenses
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md', 'License.md', 'COPYING', 'NOTICE', 'NOTICE.md'];

const out = [];
const names = [];
for (const [key, info] of Object.entries(lock.packages)) {
  if (!key || info.dev || info.optional && info.dev) continue;
  const dir = path.join(root, key);
  const pkgPath = path.join(dir, 'package.json');
  if (!fs.existsSync(pkgPath)) continue;
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  const texts = FILES.filter((f) => fs.existsSync(path.join(dir, f))).map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim());
  names.push(`${pkg.name}@${pkg.version} (${license})`);
  out.push([`${pkg.name}@${pkg.version}`, `License: ${license}`, repo ? `Source: ${repo.replace(/^git\+/, '')}` : '', '', texts.join('\n\n') || '(no licence file shipped with the package; see the source above)'].filter((x, i) => x || i === 3).join('\n'));
}

const head = `Third-party notices for Spotify Karaoke

This extension bundles the open-source packages below. Each is used under its own licence,
reproduced here as its authors require. Generated by tools/licenses.mjs from package-lock.json.

Packages: ${names.length}
`;
const body = out.sort().join('\n\n' + '='.repeat(78) + '\n\n');
fs.mkdirSync(path.join(root, 'public'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/THIRD_PARTY_NOTICES.txt'), `${head}\n${'='.repeat(78)}\n\n${body}\n`);
console.log(`${names.length} packages -> public/THIRD_PARTY_NOTICES.txt`);
const kinds = {};
for (const n of names) { const l = /\((.*)\)$/.exec(n)?.[1] ?? '?'; kinds[l] = (kinds[l] ?? 0) + 1; }
console.log(JSON.stringify(kinds));
